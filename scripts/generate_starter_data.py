#!/usr/bin/env python3
"""Generate the small, explicitly synthetic India offline starter package."""
from pathlib import Path
import csv
import hashlib
import json
import plistlib
import shutil
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ClimateLiberatorApp/ClimateLiberator/ClimateLiberator/StarterData.bundle"


def generate():
    india = DEST / "India"
    study = DEST / "Studies/India-Demo-S"
    for folder in (india / "OED", india / "demo", study):
        folder.mkdir(parents=True, exist_ok=True)
    (DEST / "Info.plist").write_bytes(plistlib.dumps({
        "CFBundleIdentifier": "com.climateliberator.starter-data",
        "CFBundleName": "Climate Liberator Synthetic India Starter",
        "CFBundlePackageType": "BNDL", "CFBundleVersion": "1"
    }))
    database = india / "india_demo.db"
    database.unlink(missing_ok=True)
    with sqlite3.connect(database) as db:
        db.executescript((ROOT / "ClimateLiberatorApp/resources/india_schema.sql").read_text())
        db.execute("INSERT INTO sources(source_id,name,category,access_mode,license_notes,created_at) VALUES(?,?,?,?,?,?)",
                   ("synthetic", "Synthetic India onboarding fixture", "demonstration", "bundled", "Generated test data, not observed building stock or insured values.", "2026-09-08"))
        db.execute("INSERT INTO datasets(dataset_id,source_id,name,geographic_scope,status,created_at) VALUES(?,?,?,?,?,?)",
                   ("synthetic-india-v1", "synthetic", "Synthetic buildings near Bengaluru", "Illustrative points in India; no national coverage", "synthetic", "2026-09-08"))
        db.execute("INSERT INTO admin_states(state_code,state_name,created_at) VALUES('KA','Karnataka','2026-09-08')")
        for index in range(12):
            db.execute("INSERT INTO building_stock(building_id,source_dataset_id,state_code,district_name,latitude,longitude,area_m2,total_built_up_m2,building_floor_count,landuse,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                       (f"SYNTHETIC-IN-{index + 1:03d}", "synthetic-india-v1", "KA", "Bengaluru (synthetic)",
                        12.9716 + (index // 4 - 1) * 0.001, 77.5946 + (index % 4 - 1.5) * 0.001,
                        100 + index * 20, 200 + index * 40, 2, "Synthetic commercial", "2026-09-08"))
        assert db.execute("SELECT count(*) FROM risk_assessments").fetchone()[0] == 0
        assert db.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
    with (india / "OED/location.csv").open("w", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["LocID", "PerilID", "Latitude", "Longitude", "AssetName", "AccNumber", "CountryCode", "CurrencyCode", "TIV_Building"])
        writer.writerow(["SYNTHETIC-IN-001", "WF", "12.9716", "77.5946", "SYNTHETIC example building", "SAMPLE-001", "IN", "INR", "1000000"])
    # Metre grid in UTM 43N, geographically near Bengaluru; no real fuel survey.
    header = "ncols 12\nnrows 12\nxllcorner 781300\nyllcorner 1435300\ncellsize 30\nNODATA_value -9999\n"
    for name, value in (("fuels", 101), ("elevation", 900), ("probabilityMap", 1)):
        (study / f"{name}.asc").write_text(header + ((" ".join([str(value)] * 12) + "\n") * 12))
        (study / f"{name}.prj").write_text("EPSG:32643\n")
    (study / "Ignitions.csv").write_text("Year,Ncell\n1,66\n")
    (study / "Weather.csv").write_text("Instance,datetime,WS,WD,FireScenario\n" + "".join(
        f"Synthetic India,{ '2020-01-01' } {hour:02d}:00,10,180,2\n" for hour in range(12, 18)))
    shutil.copyfile(ROOT / "data/ScottAndBurgan/Hom_Fuel_101_40x40-asc/spain_lookup_table.csv", study / "spain_lookup_table.csv")
    shutil.copyfile(ROOT / "Cell2Fire/tools/fuel_models/scott_burgan_table7.csv", study / "scott_burgan_table7.csv")
    (DEST / "README.md").write_text("""# Synthetic India Starter Data

This package exercises offline installation, site lookup, OED intake, and the
Scott & Burgan simulation workflow. Buildings, financial values, fuel and weather
are synthetic and are NOT an assessment of Bengaluru or national Indian risk.
There are no precomputed risk assessments or live forecasts in this package.

The 12 x 12 simulation grid uses 30 metre cells and EPSG:32643 (UTM 43N).
Its grass-fuel model is an engineering fixture, not an India-calibrated model.
The OED CSV uses Climate Liberator's current screening-intake dialect, not a
certified complete OED insurance contract. Example values are INR.

Real use requires approved exposure values, geographically matched hazard data,
appropriate vulnerability calibration, and provenance for each imported dataset.
The application copies this package to writable per-user storage on first launch.
Generated by scripts/generate_starter_data.py. Version 1.
""")
    files = {str(path.relative_to(DEST)): hashlib.sha256(path.read_bytes()).hexdigest()
             for path in sorted(DEST.rglob("*")) if path.is_file() and path.name != "manifest.json"}
    (DEST / "manifest.json").write_text(json.dumps({"schema_version": 1, "synthetic": True, "country": "IN",
                                                  "currency": "INR", "files_sha256": files}, indent=2) + "\n")
    print(DEST)


if __name__ == "__main__":
    generate()
